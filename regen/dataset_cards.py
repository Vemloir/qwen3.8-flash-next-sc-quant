def license_block():
    s = open(os.path.join(Q, "hf", "calib_splits", "chat", "README.md")).read()
    return s[s.index("## License: ODbL-1.0"):s.index("### Third-party notices")].rstrip() + "\n"


def stats(recs, part):
    n = len(recs)
    tok = sum(r["tokens"] for r in recs)
    rows = [("Total", str(n), f"{tok:,}"),
            (" / ".join(MODES), " / ".join(str(sum(r["reasoning"] == m for r in recs)) for m in MODES),
             " / ".join(f"{sum(r['tokens'] for r in recs if r['reasoning'] == m):,}" for m in MODES))]
    def counts(key, names = None):
        c = collections.Counter(r[key] for r in recs).most_common()
        return (" / ".join((names or {}).get(k, k) for k, _ in c), " / ".join(str(v) for _, v in c))
    if part == "agents":
        for key, label in (("harness", "Harness"), ("domain", "Domain")):
            a, b = counts(key)
            rows.append((f"{label}: {a}", b, ""))
        rows.append(("Longest session", "", f"{max(r['tokens'] for r in recs):,}"))
    elif part == "chat":
        a, b = counts("prompt_source", SOURCES)
        rows.append((f"Prompt source: {a}", b, ""))
        a, b = counts("lang")
        rows.append((f"Language: {a}", b, ""))
        rows.append(("Multi-turn", str(sum(r["multi_turn"] for r in recs)), ""))
    else:
        a, b = counts("source", {"cosyn": "CoSyn", "screenshot": "frontend screenshots", "pixmo": "PixMo"})
        rows.append((f"Source: {a}", b, ""))
        a, b = counts("lang")
        rows.append((f"Language of the answer: {a}", b, ""))
    head = "| | Sessions | Tokens |" if part == "agents" else "| | Rows | Tokens |"
    return head + "\n|---|---|---|\n" + "\n".join(f"| {a} | {b} | {c} |" for a, b, c in rows) + "\n", n, tok


def langs_yaml(recs):
    ls = sorted({r["lang"] for r in recs if "lang" in r} or {"en"})
    return "".join(f"- {l}\n" for l in ls)


def files_section(part, full):
    s = """## Files

- `data.jsonl`: one line per row. `id`, `tokens`, the metadata fields above, `text` (the row decoded with the
  Qwen3.8 chat template's special tokens) and `input_ids`.
- `cal_trace.safetensors`: the same rows in exllamav3 `convert.py --cal_data` format (`input_ids` right-padded to
  the longest row, `lengths`)"""
    if part == "multimodal":
        s += """, plus the images of the image rows (`mm_row`, `mm_start`, `mm_len`, `mm_image_<k>`: raw
  bytes); feeding them to the vision tower at conversion time needs a converter that supports image rows (the
  PixMo rows are text-only in this file)"""
    s += ".\n"
    if part == "multimodal":
        s += "- `images/`: the CoSyn figures and the frontend screenshots.\n"
    if full:
        s = s.replace("## Files", f"### `{part}/`")
    return s


def calib_card(part, recs, totals):
    table, n, tok = stats(recs, part)
    others = ", ".join(f"[{p}]({HF}/datasets/{REPOS[p]})" for p in REPOS)
    title = {"agents": "agent sessions", "chat": "chat", "multimodal": "images"}[part]
    return f"""---
license: odbl
pretty_name: "Qwen3.8-Flash-Next self-generated calibration data: {title}"
language:
{langs_yaml(recs) if part != "agents" else "- en\n"}tags:
- calibration
- quantization
- exl3
- self-generated
---

# Qwen3.8-Flash-Next self-generated calibration data: {title}

Part of the calibration data of the self-calibrated EXL3 quant of
[Qwen/Qwen3.8-Flash-Next]({HF}/Qwen/Qwen3.8-Flash-Next) ({MODEL}). The full set has three parts: {others},
{totals:,} tokens together. These are the rows that went into calibration; all generated rows (5.0M tokens, a
superset of these) are in [{FULL}]({HF}/datasets/{FULL}).

{DESCRIPTION[part]}

{table}
Fields: {FIELDS[part]}.

{files_section(part, False)}
{GENERATION}

## Versions

This is calibration set 2 (2026-10-18), used by the current version of the quant. Set 1 (~1M tokens, used by the
first version) is the earlier revision `{SET1[part]}` of this repository, kept only so that the first version can
be reproduced: it has reasoning cut off at a 3,072-token limit, a few looping answers and agent sessions truncated
at 25k tokens, and is not meant for any other use.

{license_block()}
### Third-party notices

{NOTICES[part]}
"""


def full_card(parts):
    tables = ""
    total = 0
    langs = set()
    for part, recs in parts.items():
        table, n, tok = stats(recs, part)
        total += tok
        langs |= {r["lang"] for r in recs if "lang" in r}
        desc = DESCRIPTION[part].replace("Each conversation appears at one reasoning\nlevel here", "Most conversations appear at two reasoning\nlevels")
        tables += f"### {part}\n\n{desc}\n\n{table}\nFields: {FIELDS[part]}.\n\n"
    files = "\n".join(files_section(p, True) for p in parts)
    notices = "\n".join(NOTICES[p] for p in parts)
    configs = "".join(f"- config_name: {p}\n  data_files: {p}/data.jsonl\n" for p in parts)
    calib = ", ".join(f"[{p}]({HF}/datasets/{REPOS[p]})" for p in REPOS)
    return f"""---
license: odbl
pretty_name: "Qwen3.8-Flash-Next self-generated traces"
language:
{"".join(f"- {l}" + chr(10) for l in sorted(langs))}tags:
- calibration
- quantization
- exl3
- self-generated
- agents
configs:
{configs}---

# Qwen3.8-Flash-Next self-generated traces

All rows generated for calibration set 2 of the self-calibrated EXL3 quant of
[Qwen/Qwen3.8-Flash-Next]({HF}/Qwen/Qwen3.8-Flash-Next) ({MODEL}): {total:,} tokens of agent sessions, chats and
image prompts, every conversation at one or more reasoning levels. The packer took 2.15M tokens of them for
calibration; those rows are published separately as {calib}.

{GENERATION}

## Parts

{tables}## Files

{files}
{license_block()}
### Third-party notices

{notices}
"""


def main(args):
    parts = {}
    for part in ("agents", "chat", "multimodal"):
        parts[part] = [json.loads(l) for l in open(os.path.join(args.input, part, "data.jsonl"))]
    lic = os.path.join(Q, "hf", "calib_splits", "chat", "LICENSE")
    if args.set == "calib":
        totals = sum(r["tokens"] for recs in parts.values() for r in recs)
        for part, recs in parts.items():
            open(os.path.join(args.input, part, "README.md"), "w").write(calib_card(part, recs, totals))
            shutil.copy(lic, os.path.join(args.input, part, "LICENSE"))
    else:
        open(os.path.join(args.input, "README.md"), "w").write(full_card(parts))
        shutil.copy(lic, os.path.join(args.input, "LICENSE"))
    print(" -- cards written in", args.input)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", choices = ("calib", "full"), required = True)
    ap.add_argument("-i", "--input", required = True)
    main(ap.parse_args())
